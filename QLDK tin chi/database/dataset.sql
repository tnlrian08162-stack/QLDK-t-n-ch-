-- F. Hiển thị danh sách các lớp học phần đã hết chỗ
SELECT 
    lhp.MaLHP,
    hp.TenHP,
    lhp.SiSoToiDa,
    lhp.SoLuongDangKy AS SoNguoiDaDangKy
FROM LopHocPhan lhp
JOIN HocPhan hp ON lhp.MaHP = hp.MaHP
WHERE lhp.SoLuongDangKy >= lhp.SiSoToiDa;
GO

--G Hiển thị danh sách sinh viên học lại, học cải thiện
SELECT 
    sv.MaSV,
    sv.HoTen,
    sv.Nganh,
    hp.TenHP AS TenMonHoc,
    dk.LoaiDangKy
FROM SinhVien sv
JOIN DangKyHocPhan dk ON sv.MaSV = dk.MaSV
JOIN LopHocPhan lhp ON dk.MaLHP = lhp.MaLHP
JOIN HocPhan hp ON lhp.MaHP = hp.MaHP
WHERE dk.LoaiDangKy IN (N'Học lại', N'Học cải thiện')
  AND dk.TrangThai = N'Thành công'
GROUP BY 
    sv.MaSV,
    sv.HoTen,
    sv.Nganh,
    hp.TenHP,
    dk.LoaiDangKy
HAVING COUNT(dk.MaLHP) >= 1
ORDER BY sv.MaSV ASC;
GO

