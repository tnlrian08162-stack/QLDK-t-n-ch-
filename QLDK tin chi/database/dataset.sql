DECLARE @MaSV VARCHAR(20);
DECLARE @SoMon INT;

DECLARE curSV CURSOR FOR
SELECT MaSV
FROM SinhVien;

OPEN curSV;
DECLARE @STT INT = 1;
FETCH NEXT FROM curSV INTO @MaSV;

WHILE @@FETCH_STATUS = 0
BEGIN

    -- mỗi SV đăng ký 4-6 môn
    SET @SoMon = 4 + ABS(CHECKSUM(NEWID())) % 3;

    DECLARE @Dem INT = 0;

    WHILE @Dem < @SoMon
    BEGIN

        DECLARE @MaLHP VARCHAR(20);
        DECLARE @MaHP VARCHAR(20);

        -- lấy ngẫu nhiên 1 lớp còn hợp lệ
        SELECT TOP 1
            @MaLHP = lhp.MaLHP,
            @MaHP  = lhp.MaHP
        FROM LopHocPhan lhp
        WHERE

        -- chưa đăng ký lớp này
        NOT EXISTS
        (
            SELECT 1
            FROM DangKyHocPhan dk
            WHERE dk.MaSV = @MaSV
              AND dk.MaLHP = lhp.MaLHP
        )

        -- chưa đăng ký học phần này
        AND NOT EXISTS
        (
            SELECT 1
            FROM DangKyHocPhan dk
            JOIN LopHocPhan lhp2
                ON dk.MaLHP = lhp2.MaLHP
            WHERE dk.MaSV = @MaSV
              AND lhp2.MaHP = lhp.MaHP
        )

        -- lớp chưa đầy
        AND (
            SELECT COUNT(*)
            FROM DangKyHocPhan dk
            WHERE dk.MaLHP = lhp.MaLHP
        ) < lhp.SiSoToiDa

        ORDER BY NEWID();

        IF @MaLHP IS NOT NULL
        BEGIN

            INSERT INTO DangKyHocPhan
            (
                MaDK,
                TrangThai,
                LoaiDangKy,
                NgayDK,
                MaSV,
                MaLHP
            )
            VALUES
            (
            CONCAT('DK', FORMAT(@STT, '0000')),
                N'Thành công',

                CASE
                    WHEN ABS(CHECKSUM(NEWID())) % 100 < 85
                        THEN N'Học mới'
                    WHEN ABS(CHECKSUM(NEWID())) % 100 < 93
                        THEN N'Học lại'
                    ELSE N'Học cải thiện'
                END,

                DATEADD
                (
                    SECOND,
                    ABS(CHECKSUM(NEWID())) %
                    DATEDIFF
                    (
                        SECOND,
                        '2026-06-11 08:00:00',
                        '2026-07-20 17:00:00'
                    ),
                    '2026-06-11 08:00:00'
                ),

                @MaSV,
                @MaLHP
            );

            SET @Dem = @Dem + 1;
            SET @STT = @STT + 1;
        END
        ELSE
        BEGIN
            BREAK;
        END

    END

    FETCH NEXT FROM curSV INTO @MaSV;

END

CLOSE curSV;
DEALLOCATE curSV;

