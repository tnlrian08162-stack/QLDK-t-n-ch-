-- A. Tìm danh sách các sinh viên chưa đăng ký bất kỳ học phần nào trong hệ thống.

SELECT 
    MaSV, 
    HoTen, 
    Nganh, 
    KhoaHoc
FROM SinhVien
WHERE MaSV NOT IN (
    SELECT DISTINCT MaSV 
    FROM DangKyHocPhan
);
GO


-- B.  Xem chi tiết Thời khóa biểu và lịch học của một sinh viên cụ thể (VD: 'SV001').
SELECT 
    sv.MaSV,
    sv.HoTen,
    hp.TenHP,
    lhp.MaLHP,
    ct.ThuHoc,
    ct.CaHoc,
    ct.PhongHoc,
    dk.TrangThai
FROM SinhVien sv
JOIN DangKyHocPhan dk ON sv.MaSV = dk.MaSV
JOIN LopHocPhan lhp ON dk.MaLHP = lhp.MaLHP
JOIN HocPhan hp ON lhp.MaHP = hp.MaHP
JOIN ChiTietLopHocPhan ct ON lhp.MaLHP = ct.MaLHP
WHERE sv.MaSV = 'SV001' AND dk.TrangThai = N'Thành công';
GO
-- C.Xem danh sách lớp của một mã lớp cụ thể (VD: 'LHP001')
SELECT 
    sv.MaSV, 
    sv.HoTen, 
    sv.Nganh, 
    dk.NgayDK
FROM SinhVien sv
JOIN DangKyHocPhan dk ON sv.MaSV = dk.MaSV
WHERE dk.MaLHP = 'LHP001' 
  AND dk.TrangThai = N'Thành công'
ORDER BY sv.MaSV; -- Chỉ cần sắp xếp, giao diện sẽ tự đánh số
GO


-- D. Kiểm tra lịch học bị trùng
SELECT 
    dk1.MaSV, 
    sv.HoTen, 
    hk.TenHK, 
    ct1.ThuHoc, 
    ct1.CaHoc, 
    ct1.MaLHP AS LopBiTrung1, 
    ct2.MaLHP AS LopBiTrung2
FROM DangKyHocPhan dk1
JOIN DangKyHocPhan dk2 ON dk1.MaSV = dk2.MaSV AND dk1.MaLHP < dk2.MaLHP
JOIN ChiTietLopHocPhan ct1 ON dk1.MaLHP = ct1.MaLHP
JOIN ChiTietLopHocPhan ct2 ON dk2.MaLHP = ct2.MaLHP
JOIN LopHocPhan lhp1 ON dk1.MaLHP = lhp1.MaLHP
JOIN LopHocPhan lhp2 ON dk2.MaLHP = lhp2.MaLHP
JOIN HocKy hk ON lhp1.MaHK = hk.MaHK
JOIN SinhVien sv ON dk1.MaSV = sv.MaSV
WHERE lhp1.MaHK = lhp2.MaHK  
  AND ct1.ThuHoc = ct2.ThuHoc 
  AND ct1.CaHoc = ct2.CaHoc
  AND dk1.TrangThai = N'Thành công' 
  AND dk2.TrangThai = N'Thành công';
GO

